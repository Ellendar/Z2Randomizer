using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace CrossPlatformUI.SourceGenerator;

[Generator]
public sealed class SettingsEnumGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context) =>
        context.RegisterSourceOutput(context.CompilationProvider, Generate);

    private static void Generate(SourceProductionContext context, Compilation compilation)
    {
        var settings = compilation.GetTypeByMetadataName("CrossPlatformUI.SerializationContext");
        var configuration = compilation.GetTypeByMetadataName("Z2Randomizer.RandomizerCore.RandomizerConfiguration");
        if (settings == null || configuration == null)
            return;

        var visited = new HashSet<ITypeSymbol>(SymbolEqualityComparer.Default);
        var enums = new List<INamedTypeSymbol>();
        foreach (var attribute in settings.GetAttributes())
        {
            if (attribute.AttributeClass?.ToDisplayString() == "System.Text.Json.Serialization.JsonSerializableAttribute" &&
                attribute.ConstructorArguments[0].Value is ITypeSymbol root)
            {
                Visit(root);
            }
        }

        var source = new StringBuilder("""
            // <auto-generated/>
            namespace CrossPlatformUI;

            public partial class SerializationContext
            {
                private static void AddSavedEnumConverters(global::System.Text.Json.JsonSerializerOptions options)
                {
            """);
        source.AppendLine();
        foreach (var type in enums.OrderBy(type => type.ToDisplayString(), StringComparer.Ordinal))
        {
            var name = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            source.AppendLine($"        options.Converters.Add(new SafeStringEnumConverter<{name}>({Fallback(type, name)}));");
        }
        source.AppendLine("    }");
        source.AppendLine("}");
        context.AddSource("SerializationContext.EnumConverters.g.cs", source.ToString());

        void Visit(ITypeSymbol type)
        {
            if (!visited.Add(type))
                return;

            if (type is IArrayTypeSymbol array)
            {
                Visit(array.ElementType);
                return;
            }
            if (type is not INamedTypeSymbol named)
                return;

            if (named.TypeKind == TypeKind.Enum)
            {
                enums.Add(named);
                return;
            }
            foreach (var argument in named.TypeArguments)
                Visit(argument);

            if (!SymbolEqualityComparer.Default.Equals(named.ContainingAssembly, compilation.Assembly) &&
                !SymbolEqualityComparer.Default.Equals(named.ContainingAssembly, configuration.ContainingAssembly))
                return;

            for (INamedTypeSymbol? current = named; current != null; current = current.BaseType)
            {
                foreach (var property in current.GetMembers().OfType<IPropertySymbol>())
                {
                    if (property.DeclaredAccessibility == Accessibility.Public && !property.IsStatic &&
                        !property.IsIndexer && !IsIgnored(property))
                    {
                        Visit(property.Type);
                    }
                }
            }
        }
    }

    private static bool IsIgnored(IPropertySymbol property) =>
        property.GetAttributes().Any(attribute =>
            attribute.AttributeClass?.ToDisplayString() == "System.Text.Json.Serialization.JsonIgnoreAttribute" &&
            // JsonIgnoreCondition.Always is 1 and is also the default.
            (attribute.NamedArguments.Length == 0 ||
             attribute.NamedArguments.Any(argument => argument.Key == "Condition" && argument.Value.Value is 1)));

    private static string Fallback(INamedTypeSymbol type, string name)
    {
        var members = type.GetMembers().OfType<IFieldSymbol>().Where(field => field.HasConstantValue).ToArray();
        if (members.Length == 0 || members.Any(field => Convert.ToDecimal(field.ConstantValue) == 0))
            return "";

        var defaultValue = type.GetAttributes().FirstOrDefault(attribute =>
            attribute.AttributeClass?.ToDisplayString() == "System.ComponentModel.DefaultValueAttribute" &&
            attribute.ConstructorArguments.Length == 1)?.ConstructorArguments[0].Value;
        var fallback = members.FirstOrDefault(field => Equals(field.ConstantValue, defaultValue)) ?? members[0];
        return $"{name}.@{fallback.Name}";
    }
}
