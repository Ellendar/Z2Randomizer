using System;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace CoreSourceGenerator;

[Generator]
public sealed class EnumMetadataGenerator : IIncrementalGenerator
{
    private const string CoreNamespace = "Z2Randomizer.RandomizerCore";
    private const string ComponentModelNamespace = "System.ComponentModel";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var enums = context.SyntaxProvider.CreateSyntaxProvider(
            static (node, _) => node is EnumDeclarationSyntax,
            static (ctx, cancellationToken) => (INamedTypeSymbol)ctx.SemanticModel.GetDeclaredSymbol(ctx.Node, cancellationToken)!)
            .Collect();

        context.RegisterSourceOutput(enums, static (ctx, symbols) => Generate(ctx, symbols));
    }

    private static void Generate(SourceProductionContext context, ImmutableArray<INamedTypeSymbol> symbols)
    {
        var enums = symbols.OrderBy(symbol => symbol.ToDisplayString(), StringComparer.Ordinal).ToImmutableArray();
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated/>");
        source.AppendLine("#nullable enable");
        source.AppendLine($"namespace {CoreNamespace};");
        source.AppendLine("internal static class EnumMetadata");
        source.AppendLine("{");

        source.AppendLine("    public static global::System.Enum? GetDefault(global::System.Type enumType)");
        source.AppendLine("    {");
        foreach (var symbol in enums)
        {
            var attribute = FindAttribute(symbol, ComponentModelNamespace + ".DefaultValueAttribute");
            if (attribute == null)
                continue;

            var enumType = symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var value = FormatConstant(attribute.ConstructorArguments[0]);
            source.AppendLine($"        if (enumType == typeof({enumType})) return ({enumType})({value});");
        }
        source.AppendLine("        return null;");
        source.AppendLine("    }");

        WriteLookup(source, enums, "GetDescription", "string?", ComponentModelNamespace + ".DescriptionAttribute",
            attribute => FormatConstant(attribute.ConstructorArguments[0]));
        WriteLookup(source, enums, "GetStringValue", "string?", CoreNamespace + ".StringValueAttribute",
            attribute => FormatConstant(attribute.ConstructorArguments[0]));
        WriteLookup(source, enums, "IsMetastyle", "bool", CoreNamespace + ".MetastyleAttribute", _ => "true");
        WriteLookup(source, enums, "GetWeight", "int?", CoreNamespace + ".DefaultWeightAttribute",
            attribute => FormatConstant(attribute.ConstructorArguments[0]));
        WriteAttributeLookup(source, enums, "GetFixedBytes", "FixedBytesAttribute");
        WriteAttributeLookup(source, enums, "GetRandomRangeDouble", "RandomRangeDoubleAttribute");
        WriteAttributeLookup(source, enums, "GetRandomRangeInt", "RandomRangeIntAttribute");
        WriteAttributeLookup(source, enums, "GetOverworldSize", "OverworldSizeMetaAttribute");
        WriteAttributeLookup(source, enums, "GetBeamSprite", "BeamSpriteMetaAttribute");

        source.AppendLine("}");
        context.AddSource("EnumMetadata.g.cs", source.ToString());
    }

    private static void WriteAttributeLookup(
        StringBuilder source, ImmutableArray<INamedTypeSymbol> enums, string method, string attributeType)
    {
        WriteLookup(source, enums, method, attributeType + "?", CoreNamespace + "." + attributeType, attribute =>
        {
            var arguments = string.Join(", ", attribute.ConstructorArguments.Select(FormatConstant));
            var initializer = string.Join(", ", attribute.NamedArguments.Select(
                argument => $"{argument.Key} = {FormatConstant(argument.Value)}"));
            return initializer.Length == 0
                ? $"new {attributeType}({arguments})"
                : $"new {attributeType}({arguments}) {{ {initializer} }}";
        });
    }

    private static void WriteLookup(
        StringBuilder source, ImmutableArray<INamedTypeSymbol> enums, string method, string returnType,
        string attributeType, Func<AttributeData, string> formatValue)
    {
        source.AppendLine();
        source.AppendLine($"    public static {returnType} {method}(global::System.Type enumType, string? memberName)");
        source.AppendLine("    {");
        foreach (var symbol in enums)
        {
            var members = symbol.GetMembers().OfType<IFieldSymbol>()
                .Select(field => (field.Name, Attribute: FindAttribute(field, attributeType)))
                .Where(member => member.Attribute != null)
                .ToArray();
            if (members.Length == 0)
                continue;

            var enumType = symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            source.AppendLine($"        if (enumType == typeof({enumType}))");
            source.AppendLine("        {");
            // Use the runtime enum member name to preserve existing selection for aliases.
            source.AppendLine("            return memberName switch");
            source.AppendLine("            {");
            foreach (var member in members)
            {
                var name = SymbolDisplay.FormatLiteral(member.Name, quote: true);
                source.AppendLine($"                {name} => {formatValue(member.Attribute!)},");
            }
            source.AppendLine($"                _ => default({returnType})");
            source.AppendLine("            };");
            source.AppendLine("        }");
        }
        source.AppendLine("        return default;");
        source.AppendLine("    }");
    }

    private static AttributeData? FindAttribute(ISymbol symbol, string attributeType) =>
        symbol.GetAttributes().FirstOrDefault(attribute => attribute.AttributeClass?.ToDisplayString() == attributeType);

    private static string FormatConstant(TypedConstant constant)
    {
        if (constant.Kind == TypedConstantKind.Array && !constant.IsNull)
        {
            var type = constant.Type!.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            return $"new {type} {{ {string.Join(", ", constant.Values.Select(FormatConstant))} }}";
        }

        if (constant.Kind == TypedConstantKind.Enum)
        {
            var type = constant.Type!.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var underlyingValue = SymbolDisplay.FormatPrimitive(constant.Value!, quoteStrings: true, useHexadecimalNumbers: false);
            return $"({type})({underlyingValue})";
        }

        return constant.ToCSharpString();
    }
}
